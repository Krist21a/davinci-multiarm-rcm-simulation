"""Stage-2b feasibility: can an articulated (EndoWrist) instrument reach the prostate targets?

Companion to prostate_access_feasibility.py, which stays untouched (roadmap requirement). Same targets,
occluders, both bladder cases, candidate port grid, camera visibility model and margins; the straight
shaft is generalised to a rigid distal segment of length Ld (wrist + jaws) that can bend at the wrist:

  The instrument is the polyline port -> W -> target. The wrist point is W = target - Ld * dir_distal,
  where dir_distal makes a bend angle theta with the shaft direction port -> W. The polyline arc length
  (port-W distance + Ld) must lie in [60, 220] mm. Clearance is checked exactly like the original:
  a centre ray along BOTH segments of the full polyline, plus a 6 mm radius sampled along the polyline
  in arc length, excluding the first 20 mm of arc (inside the wall) and the last 12 mm of arc (the jaw
  tip, the original's tip exclusion). At theta = 0 (port, W, target collinear) this degenerates to the
  verbatim original reach test; main() checks it elementwise.

Self-check (run before the tool variants, results recorded under report['self_check']):
  * port_grid_check  - candidate port count vs the stored report (see provenance note below).
  * per case         - verbatim original reach (port -> target, skip 0.02 / 0.012, radius 0.006,
                       axial step 0.001) vs the stored report's visibility, ports_reaching,
                       reachable-by-three (trio count) and feasible arrays. The stored report was
                       generated by an earlier, uncommitted draft of prostate_access_feasibility.py
                       (it lacks the `triangulable` and `seconds` keys the committed script always
                       writes, and its `candidate_ports` 5144 counts the grid BEFORE the >= 60 mm
                       ECM-port exclusion while the reach evaluation used the 5056-port filtered
                       set). The draft's reach used ~1 mm axial sampling (committed default is
                       2 mm): at step = 1 mm every quantity reproduces exactly except ONE port on
                       removed-case target 0, whose true minimum clearance is ~5.9 mm - a coin-flip
                       at the 6 mm boundary (documented residual, accepted).
  * model_check      - reach_poly(theta = 0, Ld = 12 mm) must equal the verbatim original reach
                       elementwise over the same candidates.

Variants per installed instrument (config/instruments descriptors + the arm->model mapping of
config/instruments/roles.json):
  (a) conservative: theta_max = max |wrist pitch limit|  (pitch only)
  (b) optimistic:   theta_max = acos(cos pmax * cos ymax) (combined pitch+yaw deflection)
Ld = distance from the wrist pitch AXIS (rotation axis line of <arm>_joint9) to <arm>_tcp, measured in
the verified articulated scene (scenes/davinci_si_articulated_verified.ttt), yaw unrotated to zero.
The joint-origin -> TCP point distance is reported separately (ld_origin_m) and differs: it includes
the TCP's offset along the pitch axis, which does not contribute to the swing radius. Gains are
reported per role against theta = 0 of the same model (= the original straight shaft).

Triangulation: three distinct ports, one per task role (cut_task.json roles), >= 60 mm apart, >= 60 mm
from the ECM port, shaft directions (port -> W) meeting at 20-100 deg. The current scene ports
(rcm_config rcm_world of psm1/2/3) are additionally evaluated as a fixed assignment (theta = 0 and
both variants).

Writes validation/feasibility/prostate_access_wrist.json and docs/feasibility_prostate_access_wrist.png.

Cache: the scene meshes, camera and wrist measurements are stored in --cache
(validation/feasibility/prostate_access_wrist_cache.npz, git-excluded) after the first run, which is
the only run that needs CoppeliaSim: it loads scenes/davinci_si_instruments.ttt (occluder meshes) and
scenes/davinci_si_articulated_verified.ttt (wrist geometry). Rebuild by deleting the file and running
with the simulator on the remote-API port.

Ray engine: trimesh picks ray_pyembree when the `embreex` package is installed (much faster) and
otherwise falls back to its default ray engine; results are equivalent, only runtime differs.
"""
