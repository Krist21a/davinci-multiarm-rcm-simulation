def render(cam, scene, new, pro, targets, base, report, out):
    """Painter's-algorithm endoscope view per case x variant, in the style of the original figure."""
    from PIL import Image, ImageDraw
    W, H = 640, 480
    f = (W / 2) / math.tan(math.radians(35))
    R, tcam = cam[:, :3], cam[:, 3]
    tiles = []
    for case in ('bladder_in_place', 'bladder_removed'):
        if case not in report['cases']:
            continue
        for v in ('straight', 'conservative', 'optimistic'):
            res = report['cases'][case].get(v)
            if res is None or 'summary' not in res:
                continue
            im = Image.new('RGB', (W, H + 26), 'white')
            d = ImageDraw.Draw(im)
            ctx = [(m, (205, 200, 185)) for m in base if m is not pro] + \
                  [(m['mesh'], (190, 120, 110)) for m in new.values()]
            if case == 'bladder_in_place':
                ctx.append((scene['Patient_Bladder'], (230, 200, 90)))
            tris, cols = [], []
            for m, col in ctx:
                tris.append(m.vertices[m.faces])
                cols += [col] * len(m.faces)
            fe, vv = np.array(res['feasible']), np.array(report['cases'][case]['visible'])
            dist, k = cKDTree(targets).query(pro.triangles_center)
            for di, ki in zip(dist, k):
                cols.append((40, 170, 60) if di < 0.004 and fe[ki] else
                            (240, 150, 40) if di < 0.004 and vv[ki] else
                            (200, 60, 60) if di < 0.004 else (150, 150, 165))
            tris.append(pro.vertices[pro.faces])
            T = np.vstack(tris)
            q = (T - tcam) @ R
            z = q[:, :, 2]
            good = (z > 0.005).all(axis=1)
            uv = np.stack([W / 2 - f * q[:, :, 0] / np.maximum(z, 1e-6),
                           H / 2 - f * q[:, :, 1] / np.maximum(z, 1e-6)], axis=2)
            for i in np.argsort(-z.mean(axis=1)):
                if good[i] and np.abs(uv[i]).max() < 4 * W:
                    d.polygon([tuple(x) for x in uv[i]], fill=cols[i])
            d.rectangle([0, H, W, H + 26], fill='white')
            s = res['summary']
            d.text((6, H + 6), f"{case} {v}: feasible +x {s['+x']['feasible']}/{s['+x']['targets']}, "
                               f"-x {s['-x']['feasible']}/{s['-x']['targets']}  "
                               'green feasible / orange visible only / red not visible', fill='black')
            tiles.append(im)
    if not tiles:
        return
    sheet = Image.new('RGB', (W * len(tiles), H + 26), 'white')
    for i, t in enumerate(tiles):
        sheet.paste(t, (i * W, 0))
    out.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(out)


