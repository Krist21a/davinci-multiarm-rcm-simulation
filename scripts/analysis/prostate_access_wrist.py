unit = pa.unit


def ortho_basis(d0):
    """Per-row orthonormal (k1, k2) spanning the plane perpendicular to unit rows d0 (N,3)."""
    k1 = np.cross(d0, np.tile([0.0, 0.0, 1.0], (len(d0), 1)))
    n = np.linalg.norm(k1, axis=1)
    bad = n < 1e-9
    if bad.any():
        k1[bad] = np.cross(d0[bad], np.tile([1.0, 0.0, 0.0], (int(bad.sum()), 1)))
        n = np.linalg.norm(k1, axis=1)
    k1 /= n[:, None]
    return k1, np.cross(d0, k1)


def clear_poly(occ, A, M, B, radius, step=STEP, skip_start=WALL_SKIP, skip_end=TIP_SKIP):
    """Occluder clearance for the polyline A -> M -> B, mirroring pa.Occluder.clear.

    Centre-ray tests on BOTH segments (full length, like the original's ray test which ignores the
    skip margins) and `radius` distance sampling along the polyline in ARC length, with the first
    `skip_start` of arc and the last `skip_end` of arc unsampled - the original's wall and jaw-tip
    exclusions respectively. The sampling formula is identical to the original's (counts =
    floor(window/step), s = window_lo + step * arange(counts)), so for collinear A, M, B the queried
    positions are byte-for-byte the same ones a single-segment call would produce.
    """
    A, M, B = np.atleast_2d(np.asarray(A, float)), np.atleast_2d(np.asarray(M, float)), np.atleast_2d(np.asarray(B, float))
    n = len(A)
    L1 = np.linalg.norm(M - A, axis=1)
    L2 = np.linalg.norm(B - M, axis=1)
    ok = (L1 > 1e-9) & (L2 > 1e-9)
    u1 = np.where(L1[:, None] > 0, (M - A) / np.maximum(L1, 1e-30)[:, None], 0.0)
    u2 = np.where(L2[:, None] > 0, (B - M) / np.maximum(L2, 1e-30)[:, None], 0.0)
    # --- centre rays on both segments, batched (chunked: one huge call OOMs trimesh) ---
    live = np.nonzero(ok)[0]
    for c0 in range(0, len(live), 512):
        c = live[c0:c0 + 512]
        O = np.vstack([A[c] + u1[c] * 1e-4, M[c] + u2[c] * 1e-4])
        D = np.vstack([u1[c], u2[c]])
        lim = np.concatenate([L1[c], L2[c]])
        locs, ridx, _ = occ.ray_mesh.ray.intersects_location(O, D, multiple_hits=False)
        if len(ridx):
            hit = np.linalg.norm(locs - O[ridx], axis=1) < lim[ridx] - 1e-4
            blocked = np.zeros(2 * len(c), bool)
            blocked[ridx[hit]] = True
            ok[c[blocked[:len(c)]]] = False
            ok[c[blocked[len(c):]]] = False
    # --- radius sampling along the polyline in ARC length ---
    # Samples are placed at the global arc positions s = skip_start + step * k,
    # k < floor((arc - skip_end - skip_start) / step) - the exact formula the original applies to a
    # single segment - then mapped onto whichever segment contains them. For collinear A, M, B the
    # queried positions are identical to the original's for ANY Ld.
    if radius > 0:
        arc = L1 + L2
        idx = np.nonzero(ok)[0]
        counts = np.maximum(np.floor((arc[idx] - skip_end - skip_start) / step).astype(np.int64), 0)
        keep = counts > 0
        kidx, kcounts = idx[keep], counts[keep]
        if len(kidx):
            seg = np.repeat(np.arange(len(kidx)), kcounts)
            s = skip_start + step * (np.arange(kcounts.sum()) -
                                     np.repeat(np.cumsum(kcounts) - kcounts, kcounts))
            base = kidx[seg]
            on1 = s <= L1[base] - 1e-12
            P = np.empty((len(s), 3))
            P[on1] = A[base[on1]] + s[on1, None] * u1[base[on1]]
            P[~on1] = M[base[~on1]] + (s[~on1] - L1[base[~on1]])[:, None] * u2[base[~on1]]
            dist, _ = occ.tree.query(P, distance_upper_bound=radius)
            blocked = np.zeros(n, bool)
            np.logical_or.at(blocked, base, np.isfinite(dist))
            ok &= ~blocked
    return ok


def reach_poly(occ, ports, target, Ld, theta_max, radius=SHAFT_RADIUS):
    """Bent-distal reachability of `target` from each of `ports` (N,3) against Occluder `occ`.

    The instrument is the polyline port -> W -> target with W = target - Ld * dir_distal and
    arc length |port-W| + Ld constrained to RANGE. Returns a list of None or
    dict(port, wrist, shaft_dir, distal_dir, bend_rad, port_w_m, arc_m) per port; the first passing
    sample in enumeration order (theta ascending, azimuth ascending). theta = 0 is the original
    straight-shaft model exactly (port, W, target collinear).
    """
    ports = np.asarray(ports, float)
    t = np.asarray(target, float)
    v = t - ports
    D = np.linalg.norm(v, axis=1)
    keep = (D > 1e-6) & (D <= RANGE[1] + 1e-9)   # arc = |port-W| + Ld >= |port-target| by triangle inequality
    recs = [None] * len(ports)
    idx = np.nonzero(keep)[0]
    if not len(idx):
        return recs
    d0 = unit(v[idx])
    groups = [(d0, np.arange(len(d0)))]                      # theta = 0 first
    if theta_max > 0:
        k1, k2 = ortho_basis(d0)
        for frac in BEND_FRACS:
            th = theta_max * frac
            dirs = np.stack([d0 * math.cos(th) + math.sin(th) * (k1 * math.cos(2 * np.pi * a / N_AZ) +
                                                                 k2 * math.sin(2 * np.pi * a / N_AZ))
                             for a in range(N_AZ)])          # (N_AZ, N, 3)
            groups += [(dirs[a], np.arange(len(d0))) for a in range(N_AZ)]
    live = np.arange(len(idx))                              # local indices still unresolved
    for gdir, gowner in groups:
        if not len(live):
            break
        sel = np.isin(gowner, live)
        dirs_g, owner_g = gdir[sel], gowner[sel]
        P = ports[idx][owner_g]
        W = t - Ld * dirs_g
        s = unit(W - P)
        Lw = np.linalg.norm(W - P, axis=1)
        bend = np.arccos(np.clip((s * dirs_g).sum(axis=1), -1.0, 1.0))
        arc = Lw + Ld
        ok = ((bend <= theta_max + 1e-6) & (arc >= RANGE[0] - 1e-9) & (arc <= RANGE[1] + 1e-9))
        clear = np.zeros(len(P), bool)
        oki = np.nonzero(ok)[0]
        for c0 in range(0, len(oki), 256):        # chunk: polyline check is 2 rays + radius query
            c = oki[c0:c0 + 256]
            clear[c] = clear_poly(occ, P[c], W[c], np.repeat(t[None], len(c), axis=0), radius)
        for j in np.nonzero(clear)[0]:
            i = int(idx[owner_g[j]])
            if recs[i] is None:
                recs[i] = dict(port=ports[i].tolist(), wrist=W[j].tolist(), shaft_dir=s[j].tolist(),
                               distal_dir=dirs_g[j].tolist(), bend_rad=float(bend[j]),
                               port_w_m=float(Lw[j]), arc_m=float(arc[j]))
        live = live[~np.isin(live, owner_g[clear])]
    return recs


def reach_orig(occ, ports, target):
    """The original analysis's straight-shaft reach test verbatim (step = STEP, see module docstring):
    candidates are ports with |port - target| in RANGE; a port reaches if occ.clear passes."""
    ports = np.asarray(ports, float)
    t = np.asarray(target, float)
    L = np.linalg.norm(t - ports, axis=1)
    sel = (L >= RANGE[0]) & (L <= RANGE[1])
    cand = ports[sel]
    ok = np.zeros(len(ports), bool)
    if len(cand):
        ok[sel] = occ.clear(cand, np.repeat(t[None], len(cand), axis=0), SHAFT_RADIUS,
                            skip_start=WALL_SKIP, skip_end=TIP_SKIP, step=STEP)
    return sel, ok


def trio_straight(good, dirs, seed, tries=400):
    """Original sampling: `tries` random 3-subsets of `good` ports (rng seeded per target), pairwise
    >= PORT_SEP apart and shaft directions meeting at MEET_DEG. Returns the port triple or None."""
    rng = np.random.default_rng(seed)
    for _ in range(tries):
        trio = rng.choice(len(good), 3, replace=False)
        if all(np.linalg.norm(good[i] - good[j]) >= PORT_SEP and
               MEET_DEG[0] <= math.degrees(math.acos(np.clip(dirs[i] @ dirs[j], -1, 1))) <= MEET_DEG[1]
               for i, j in itertools.combinations(trio, 2)):
            return good[trio]
    return None


def trio_roles(recs_by_role, ecm_port):
    """Deterministic exhaustive search: one reaching port per role, three distinct ports >= PORT_SEP
    from the ECM port and pairwise, meeting angles within MEET_DEG between the accepted shaft dirs."""
    lists = []
    for recs in recs_by_role:
        idx = [i for i, r in enumerate(recs)
               if r is not None and np.linalg.norm(np.asarray(r['port']) - ecm_port) >= PORT_SEP - 1e-12]
        lists.append(idx)
        if not idx:
            return None
    for combo in itertools.product(*lists):
        if len(set(combo)) < 3:
            continue
        ports = [np.asarray(recs_by_role[r][combo[r]]['port']) for r in range(3)]
        sdirs = [np.asarray(recs_by_role[r][combo[r]]['shaft_dir']) for r in range(3)]
        if all(np.linalg.norm(ports[a] - ports[b]) >= PORT_SEP - 1e-12 and
               MEET_DEG[0] <= math.degrees(math.acos(np.clip(sdirs[a] @ sdirs[b], -1, 1))) <= MEET_DEG[1]
               for a, b in itertools.combinations(range(3), 2)):
            return combo
    return None


def read_inputs(args):
    """Scene meshes/camera/skin frame plus wrist geometry; cached in --cache so re-runs need no simulator.

    The wrist measurement reads the world matrices of <arm>_joint9 (wrist pitch), <arm>_wrist_yaw_joint
    and <arm>_tcp in the verified articulated scene, plus the current joint positions. Ld is the
    PERPENDICULAR distance from the pitch-axis LINE (joint origin + local z axis, the CoppeliaSim
    rotation axis) to the TCP, with the TCP un-rotated about the yaw axis to yaw = 0 (the rigid
    distance is yaw-dependent; the neutral value is the model's Ld). The joint-origin -> TCP point
    distance (ld_origin_m) is kept for comparison: it includes the TCP's axial offset along the pitch
    axis, which never contributes to the swing radius.
    """
    if args.cache and Path(args.cache).exists():
        z = np.load(args.cache, allow_pickle=True)
        payload = z['payload'].item()
        if payload.get('wrist') and all('pitch_axis' in payload['wrist'][a] for a in ARMS):
            return payload
        print('stale cache (pre-axis wrist measurement); rebuilding', flush=True)
    payload = {}
    payload['scene'] = pa.read_scene(args, None)
    client, sim = connect(args)
    load_scene(client, sim, args, ARTICULATED_SCENE, 'feasibility_wrist_instr.ttt')
    by = aliases(sim)
    wrist = {}
    for arm in ARMS:
        pitch = f'{arm}_joint9'
        yaw = f'{arm}_wrist_yaw_joint'
        roll = f'{arm}_joint8'
        tcp = f'{arm}_tcp'
        missing = [n for n in (pitch, yaw, roll, tcp) if n not in by]
        if missing:
            raise SystemExit(f'{arm}: missing {missing} in {ARTICULATED_SCENE.name}')
        M9 = matrix_to_np(sim.getObjectMatrix(by[pitch], -1))
        My = matrix_to_np(sim.getObjectMatrix(by[yaw], -1))
        M8 = matrix_to_np(sim.getObjectMatrix(by[roll], -1))
        Mt = matrix_to_np(sim.getObjectMatrix(by[tcp], -1))
        p9, py, p8, pt = M9[:, 3], My[:, 3], M8[:, 3], Mt[:, 3]
        a9, ay, a8 = unit(M9[:, 2]), unit(My[:, 2]), unit(M8[:, 2])
        q_pitch = float(sim.getJointPosition(by[pitch]))
        q_yaw = float(sim.getJointPosition(by[yaw]))
        # Un-rotate TCP about the yaw axis to yaw = 0 (Rodrigues).
        q = -q_yaw
        v = pt - py
        T0 = py + v * math.cos(q) + np.cross(ay, v) * math.sin(q) + ay * (ay @ v) * (1.0 - math.cos(q))
        ld = float(np.linalg.norm((T0 - p9) - ((T0 - p9) @ a9) * a9))
        wrist[arm] = dict(
            ld_m=ld,
            ld_origin_m=float(np.linalg.norm(pt - p9)),
            pitch_joint=pitch, yaw_joint=yaw, tcp=tcp,
            pitch_pos=p9.tolist(), pitch_axis=a9.tolist(),
            yaw_pos=py.tolist(), yaw_axis=ay.tolist(), roll_axis=a8.tolist(),
            tcp_pos=pt.tolist(), q_pitch_rad=q_pitch, q_yaw_rad=q_yaw,
            pitch_to_yaw_origin_m=float(np.linalg.norm(py - p9)),
            tcp_to_yaw_axis_m=float(np.linalg.norm((pt - py) - ((pt - py) @ ay) * ay)),
            pitch_axis_x_roll_axis=float(a9 @ a8))
    payload['wrist'] = wrist
    if args.cache:
        Path(args.cache).parent.mkdir(parents=True, exist_ok=True)
        np.savez_compressed(args.cache, payload=np.array(payload, dtype=object))
    return payload


def load_tools(roles_cfg):
    """Per-role tool parameters from roles.json arm->model mapping + the instrument descriptors."""
    arms_map = pa.read_json(REPO / 'config' / 'instruments' / 'roles.json')['arms']
    tools = {}
    for role in ROLES:
        arm = roles_cfg[role]
        model = arms_map[arm]['instrument']
        kin = pa.read_json(REPO / 'config' / 'instruments' / f'{model}.json')['kinematics']
        pmax = max(abs(x) for x in kin['wrist_pitch_limits_rad'])
        ymax = max(abs(x) for x in kin['wrist_yaw_limits_rad'])
        tools[role] = dict(arm=arm, model=model, pitch_limit_rad=pmax, yaw_limit_rad=ymax,
                           theta_conservative_rad=pmax,
                           theta_optimistic_rad=float(math.acos(np.clip(math.cos(pmax) * math.cos(ymax), -1, 1))))
    return tools


def evaluate_case(occ, targets, ports, ecm_port, tools, wrist, current_ports, t_start):
    """Full evaluation of one occluder case: visibility (original model verbatim), the verbatim
    original reach (self-check), the polyline theta=0 model-consistency check, per-role theta=0
    baselines, both wrist variants per role, and the current-port fixed assignment."""
    n = len(targets)
    vis = np.zeros(n, bool)
    reach_straight = np.zeros(n, int)
    tri_straight = np.zeros(n, bool)
    model_match = np.zeros(n, bool)
    theta0 = {r: np.zeros(n, int) for r in ROLES}
    variants = {v: dict(role_ports={r: [] for r in ROLES}, role_recs={r: [] for r in ROLES},
                        role_reach={r: np.zeros(n, int) for r in ROLES},
                        triangulable=np.zeros(n, bool), trios=[None] * n)
                for v in ('conservative', 'optimistic')}
    current = {a: {v: np.zeros(n, bool) for v in ('straight', 'conservative', 'optimistic')}
               for a in ARMS}

    for ti, t in enumerate(targets):
        # --- visibility: verbatim from the original (same tip grid, same clearance calls) ---
        to_t = unit(t - ecm_port)
        k1 = unit(np.cross(to_t, [0, 0, 1.0]))
        k2 = np.cross(to_t, k1)
        tips = []
        for depth in (0.05, 0.08, 0.11, 0.14, 0.17):
            for tilt in (0.0, 15.0, 30.0, 45.0):
                for az in (range(0, 360, 45) if tilt else [0]):
                    a = math.radians(az)
                    d = unit(to_t * math.cos(math.radians(tilt)) + math.sin(math.radians(tilt)) *
                             (k1 * math.cos(a) + k2 * math.sin(a)))
                    tip = ecm_port + depth * d
                    view = t - tip
                    dist = np.linalg.norm(view)
                    if 0.025 <= dist <= 0.15 and np.degrees(np.arccos(np.clip(view @ d / dist, -1, 1))) <= 65:
                        tips.append(tip)
        if tips:
            tips = np.array(tips)
            sight = occ.clear(tips, np.repeat(t[None], len(tips), axis=0), 0.0)
            if sight.any():
                path = occ.clear(np.repeat(ecm_port[None], sight.sum(), axis=0), tips[sight], 0.008,
                                 skip_start=0.03)
                vis[ti] = bool(path.any())
        # --- verbatim original reach (self-check baseline) ---
        sel, ok = reach_orig(occ, ports, t)
        good = ports[ok]
        reach_straight[ti] = len(good)
        ecm_ok = len(good) and (np.linalg.norm(good - ecm_port, axis=1) >= PORT_SEP)
        if len(good) and ecm_ok.sum() >= 3:
            g2, d2 = good[ecm_ok], unit(t - good[ecm_ok])
            tri_straight[ti] = trio_straight(g2, d2, seed=ti) is not None
        # --- model consistency: polyline at theta=0, Ld=12 mm must equal the straight reach ---
        recs0 = reach_poly(occ, ports[sel], t, SELF_CHECK['Ld'], SELF_CHECK['theta_max'])
        model_match[ti] = np.array_equal(np.array([r is not None for r in recs0]), ok[sel])
        # --- per-role theta=0 baseline (gains reference) and wrist variants ---
        for r in ROLES:
            rec = reach_poly(occ, ports, t, wrist[tools[r]['arm']]['ld_m'], 0.0)
            theta0[r][ti] = sum(x is not None for x in rec)
        for v in variants:
            thkey = 'theta_conservative_rad' if v == 'conservative' else 'theta_optimistic_rad'
            recs_role = []
            for r in ROLES:
                tool = tools[r]
                rec = reach_poly(occ, ports, t, wrist[tool['arm']]['ld_m'], tool[thkey])
                recs_role.append(rec)
                variants[v]['role_ports'][r].append([i for i, rr in enumerate(rec) if rr is not None])
                variants[v]['role_recs'][r].append(rec)
                variants[v]['role_reach'][r][ti] = sum(rr is not None for rr in rec)
            combo = trio_roles(recs_role, ecm_port)
            if combo is not None:
                variants[v]['triangulable'][ti] = True
                variants[v]['trios'][ti] = [dict(role=ROLES[r], **{k: recs_role[r][combo[r]][k]
                                                                   for k in ('port', 'wrist', 'bend_rad',
                                                                             'port_w_m', 'arc_m')})
                                            for r in range(3)]
        # --- current scene ports as a fixed assignment ---
        for arm in ARMS:
            tool = next(tl for tl in tools.values() if tl['arm'] == arm)
            ld = wrist[arm]['ld_m']
            for v, th in (('straight', 0.0), ('conservative', tool['theta_conservative_rad']),
                          ('optimistic', tool['theta_optimistic_rad'])):
                rec = reach_poly(occ, current_ports[arm][None], t, ld, th)
                current[arm][v][ti] = rec[0] is not None
        print(f'  target {ti}/{n} t={time.time() - t_start:.0f}s', flush=True)
    return dict(vis=vis, reach_straight=reach_straight, tri_straight=tri_straight,
                model_match=model_match, theta0=theta0, variants=variants, current=current)


def check_baseline(res, baseline_case):
    """Self-check: this run's verbatim-original reach/visibility results vs the stored report.

    visible, reachable_by_3 (trio count), feasible and the visible array must match exactly.
    ports_reaching may differ only inside the documented boundary residual (|diff| <= 1 per target,
    one ~5.9 mm-clearance port on removed target 0); every differing cell is recorded.
    """
    exp_reach = [int(x) for x in baseline_case['ports_reaching']]
    got_reach = [int(x) for x in res['reach_straight']]
    diff = [i for i, (g, e) in enumerate(zip(got_reach, exp_reach)) if g != e]
    got = dict(visible=int(res['vis'].sum()), visible_array=[bool(x) for x in res['vis']],
               ports_reaching=got_reach,
               reachable_by_3=int(res['tri_straight'].sum()),
               feasible=[bool(x) for x in (res['vis'] & res['tri_straight'])])
    exp = dict(visible=int(sum(baseline_case['visible'])),
               visible_array=[bool(x) for x in baseline_case['visible']],
               ports_reaching=exp_reach,
               reachable_by_3=int(sum(s['reachable_by_3'] for s in baseline_case['summary'].values())),
               feasible=[bool(x) for x in baseline_case['feasible']])
    residual = [dict(target=int(i), got=got_reach[i], expected=exp_reach[i]) for i in diff]
    exact_parts = (got['visible'] == exp['visible'] and got['visible_array'] == exp['visible_array']
                   and got['reachable_by_3'] == exp['reachable_by_3'] and got['feasible'] == exp['feasible'])
    reach_ok = all(abs(got_reach[i] - exp_reach[i]) <= 1 for i in diff)
    return got, exp, dict(residual_ports=residual, ok=bool(exact_parts and reach_ok),
                          exact=bool(exact_parts and not diff))


