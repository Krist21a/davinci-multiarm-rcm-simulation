# Original model margins (identical to prostate_access_feasibility).
SHAFT_RADIUS = 0.006
WALL_SKIP = 0.02
TIP_SKIP = 0.012            # original 12 mm jaw-tip radius exclusion (last 12 mm of arc length)
RANGE = (0.06, 0.22)        # original port-target bounds; applied to the polyline arc length
STEP = 0.001                # axial sampling step; the stored report's draft used ~1 mm (committed: 2 mm)
PORT_SEP = 0.06
MEET_DEG = (20.0, 100.0)
